  version "0.153.0"

  on_macos do
    if Hardware::CPU.arm?
      url "https://github.com/vinhnx/vtcode/releases/download/#{version}/vtcode-#{version}-aarch64-apple-darwin.tar.gz"
      sha256 "45e0e36741bc228ad650a4f7283daea6d7cb43d76005085f4b73947736a38bb1"
